"""
Password-reset tokens (Daniel).

Design
------
1. A token is 32 random bytes from Python's `secrets` module (the module
   meant for security), encoded for URLs -> ~43 characters. Guessing one is
   practically impossible.
2. Only the SHA-256 HASH of the token is stored in MySQL. The raw token is
   only ever in the email link. If someone steals the database, they still
   cannot build a working reset link.
3. Each token has expires_at (default 30 minutes) and used_at (NULL until used).
4. Using a token is done with ONE conditional UPDATE:
       UPDATE ... SET used_at = now WHERE token_id = ? AND used_at IS NULL
                                       AND expires_at > now
   If two requests arrive at the same moment, MySQL lets only one of them
   change the row; the other sees 0 rows affected and is rejected. The new
   password is saved in the SAME transaction, so either both happen or
   neither does.
5. After a successful reset, all other unused tokens for that user are
   invalidated too.

All times are UTC and generated by Python, so the MySQL server's time zone
does not matter.
"""
import hashlib
import secrets
from datetime import datetime, timedelta, timezone

from .db import execute, query_one, transaction

# Reasons a token can be rejected (used by the route to pick a message)
INVALID = "invalid"
EXPIRED = "expired"
USED = "used"


def utcnow():
    """Current UTC time without tzinfo (MySQL DATETIME has no time zone)."""
    return datetime.now(timezone.utc).replace(tzinfo=None, microsecond=0)


def hash_token(raw_token: str) -> str:
    return hashlib.sha256(raw_token.encode("utf-8")).hexdigest()


def count_recent_requests(user_id, window_minutes) -> int:
    since = utcnow() - timedelta(minutes=window_minutes)
    row = query_one(
        "SELECT COUNT(*) AS n FROM password_reset_tokens "
        "WHERE user_id = %s AND created_at >= %s",
        (user_id, since),
    )
    return int(row["n"]) if row else 0


def create_reset_token(user_id, expiry_minutes):
    """
    Create and store a new token. Returns (raw_token, expires_at).
    The raw token must go ONLY into the email link - never log it.
    """
    raw_token = secrets.token_urlsafe(32)
    now = utcnow()
    expires_at = now + timedelta(minutes=expiry_minutes)
    execute(
        "INSERT INTO password_reset_tokens (user_id, token_hash, created_at, expires_at) "
        "VALUES (%s, %s, %s, %s)",
        (user_id, hash_token(raw_token), now, expires_at),
    )
    return raw_token, expires_at


def check_token(raw_token):
    """
    Look up a token WITHOUT using it (for showing the reset form).
    Returns (token_row, None) if valid, or (None, reason) if not.
    """
    if not raw_token or len(raw_token) > 200:
        return None, INVALID
    row = query_one(
        "SELECT t.token_id, t.user_id, t.expires_at, t.used_at, u.email, u.password_hash "
        "FROM password_reset_tokens t "
        "JOIN users u ON u.user_id = t.user_id "      # JOIN = the user must still exist
        "WHERE t.token_hash = %s",
        (hash_token(raw_token),),
    )
    if row is None:
        return None, INVALID
    if row["used_at"] is not None:
        return None, USED
    if row["expires_at"] <= utcnow():
        return None, EXPIRED
    return row, None


def consume_token_and_set_password(raw_token, new_password_hash):
    """
    Atomically: mark the token used, save the new password hash and
    invalidate the user's other outstanding tokens.
    Returns (True, None) on success or (False, reason).
    """
    row, reason = check_token(raw_token)
    if row is None:
        return False, reason

    now = utcnow()
    try:
        return _consume(row, new_password_hash, now)
    except _UserGone:
        return False, INVALID


class _UserGone(Exception):
    pass


def _consume(row, new_password_hash, now):
    with transaction() as cur:
        # Claim the token. Only succeeds if it is STILL unused and unexpired.
        claimed = cur.execute(
            "UPDATE password_reset_tokens SET used_at = %s "
            "WHERE token_id = %s AND used_at IS NULL AND expires_at > %s",
            (now, row["token_id"], now),
        )
        if claimed != 1:
            # Someone else used it a split second earlier, or it just expired.
            # Leaving the block normally commits nothing harmful (0 rows changed).
            return False, USED

        updated = cur.execute(
            "UPDATE users SET password_hash = %s WHERE user_id = %s",
            (new_password_hash, row["user_id"]),
        )
        if updated != 1:
            # User vanished mid-request: undo the token claim as well.
            raise _UserGone()

        # Invalidate any other unused links for this account
        cur.execute(
            "UPDATE password_reset_tokens SET used_at = %s "
            "WHERE user_id = %s AND used_at IS NULL",
            (now, row["user_id"]),
        )
    return True, None


def delete_old_tokens(older_than_days=7) -> int:
    """Housekeeping: remove expired/used tokens older than N days."""
    cutoff = utcnow() - timedelta(days=older_than_days)
    affected, _ = execute(
        "DELETE FROM password_reset_tokens WHERE expires_at < %s",
        (cutoff,),
    )
    return affected
